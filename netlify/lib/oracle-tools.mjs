const VOWELS = new Set(["Α","Ε","Η","Ι","Ο","Υ","Ω","A","E","I","O","U","Y"]);
const strip = (s) => String(s || "").normalize("NFD").replace(/[̀-ͯ]/g, "").toUpperCase();
function reduce(n, keepMaster = true) {
  while (n > 9 && !(keepMaster && (n === 11 || n === 22 || n === 33))) {
    n = String(n).split("").reduce((a, d) => a + +d, 0);
  }
  return n;
}
function letterSum(name, onlyVowels) {
  let total = 0;
  for (const ch of strip(name)) {
    if (onlyVowels && !VOWELS.has(ch)) continue;
    total += GREEK_MAP[ch] || LATIN_MAP[ch] || 0;
  }
  return total;
}
function numerologyData(p, now = new Date()) {
  const [y, m, d] = String(p.dob1).split("-").map(Number);
  const lifePath = reduce(String(p.dob1).replace(/-/g, "").split("").reduce((a, c) => a + +c, 0));
  const nameNumber = reduce(letterSum(p.name1) || 1);
  const soulNumber = reduce(letterSum(p.name1, true) || 1);
  const year = now.getFullYear();
  const personalYear = reduce(d + m + String(year).split("").reduce((a, c) => a + +c, 0), false);
  const nextPersonalYear = reduce(d + m + String(year + 1).split("").reduce((a, c) => a + +c, 0), false);
  return { lifePath, nameNumber, soulNumber, year, personalYear, nextPersonalYear };
}
